static u16 nextTile;
static u32 tileBuf[16 * 8];     /* up to 4x4 tiles */

static u8 nibble(char c)
{
    if (c >= '1' && c <= '9') return c - '0';
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return 0;
}

/* Convert text art of w x h tiles to 4bpp, column-major (sprite order) */
static void convert(const char* const* rows, u16 w, u16 h)
{
    for (u16 tx = 0; tx < w; tx++)
    {
        for (u16 ty = 0; ty < h; ty++)
        {
            for (u16 py = 0; py < 8; py++)
            {
                const char* row = rows[ty * 8 + py];
                u16 len = strlen(row);
                u32 v = 0;

                for (u16 px = 0; px < 8; px++)
                {
                    u16 i = tx * 8 + px;
                    v = (v << 4) | ((i < len) ? nibble(row[i]) : 0);
                }
                tileBuf[((tx * h) + ty) * 8 + py] = v;
            }
        }
    }
}

static u16 upload(u16 num)
{
    u16 idx = nextTile;

    VDP_loadTileData(tileBuf, idx, num, CPU);
    nextTile += num;
    return idx;
}

static u16 load(const char* const* rows, u16 w, u16 h)
{
    convert(rows, w, h);
    return upload(w * h);
}

/* Build a 32x32 symmetric image from its left half */
static char mirrorBuf[32][33];
static const char* mirrorRows[32];

static u16 loadMirrored(const char* const* half)
{
    for (u16 y = 0; y < 32; y++)
    {
        const char* src = half[y];

        for (u16 x = 0; x < 16; x++)
        {
            mirrorBuf[y][x] = src[x];
            mirrorBuf[y][31 - x] = src[x];
        }
        mirrorBuf[y][32] = 0;
        mirrorRows[y] = mirrorBuf[y];
    }
    return load(mirrorRows, 4, 4);
}

/* Score pop-up: 3 digit number, white, 16x8 sprite */
static u16 loadPoints(u16 value)
{
    static char rowsBuf[8][17];
    static const char* rows[8];
    u16 d[3] = { value / 100, (value / 10) % 10, value % 10 };

    for (u16 y = 0; y < 8; y++)
    {
        memset(rowsBuf[y], '.', 16);
        rowsBuf[y][16] = 0;
        rows[y] = rowsBuf[y];
    }
    for (u16 n = 0; n < 3; n++)
    {
        for (u16 y = 0; y < 5; y++)
            for (u16 x = 0; x < 3; x++)
                if (digits3x5[d[n]][y][x] == '1') rowsBuf[y + 1][1 + n * 5 + x] = '4';
    }
    return load(rows, 2, 1);
}

/* Girder split in two tiles when it is not aligned on the 8 pixel grid */
static void loadGirderVariants(void)
{
    u32 base[8];

    convert(artGirder, 1, 1);
    memcpy(base, tileBuf, sizeof(base));
    tGirder = upload(1);

    tGirderTop = nextTile - 1;      /* so tGirderTop + o is valid for o = 1..7 */
    for (u16 o = 1; o < 8; o++)
    {
        for (u16 y = 0; y < 8; y++) tileBuf[y] = (y >= o) ? base[y - o] : 0;
        upload(1);
    }
    tGirderBot = nextTile - 1;
    for (u16 o = 1; o < 8; o++)
    {
        for (u16 y = 0; y < 8; y++) tileBuf[y] = (y < o) ? base[8 - o + y] : 0;
        upload(1);
    }
}

